arvud = [10, 20, 30, 40, 50, 60, 70, 80]

# 1. Esimesed kolm elementi
print(arvud[:3])

# 2. Viimased kolm elementi
print(arvud[-3:])

# 3. Indeksid 2 kuni 5 (kaasa arvatud)
print(arvud[2:6])

# 4. Kõik peale esimese
print(arvud[1:])

# 5. Kõik peale viimase
print(arvud[:-1])

# 6. Vastupidine järjekord
print(arvud[::-1])